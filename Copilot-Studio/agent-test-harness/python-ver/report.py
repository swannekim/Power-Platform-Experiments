"""
report.py — turns results.json into a Markdown report (README.md)
-----------------------------------------------------------------
The report is designed to be committed straight to a GitHub repo as README.md,
so the repo's front page always shows the latest test run. GitHub renders the
tables and the shields.io status badge automatically.
"""

from __future__ import annotations


def _badge(passed: int, total: int) -> str:
    colour = "brightgreen" if passed == total else ("yellow" if passed >= total * 0.7 else "red")
    label = f"{passed}%2F{total}%20passing"
    return f"![tests](https://img.shields.io/badge/tests-{label}-{colour})"


def write_report(payload: dict, path: str = "README.md") -> None:
    results = payload["functional"]
    passed = sum(1 for r in results if r["passed"])
    total = len(results)

    lines: list[str] = []
    A = lines.append

    A(f"# 🤖 {payload['agent_name']} — Automated Test Report")
    A("")
    A(_badge(passed, total))
    A("")
    A(f"**Last run:** {payload['generated_at']}  ")
    A(f"**Result:** {passed}/{total} functional cases passing")
    A("")
    A("> Auto-generated by the Direct Line test harness. See **[SETUP.md](SETUP.md)** "
      "for how it works and how to configure it.")
    A("")

    # ---- Summary by category -------------------------------------------
    A("## Summary by category")
    A("")
    A("| Category | Passing | Total |")
    A("|---|---|---|")
    cats: dict[str, list] = {}
    for r in results:
        cats.setdefault(r["category"], []).append(r)
    for cat, rs in sorted(cats.items()):
        p = sum(1 for r in rs if r["passed"])
        A(f"| {cat} | {p} | {len(rs)} |")
    A("")

    # ---- Functional detail ---------------------------------------------
    A("## Functional results")
    A("")
    A("| | Case | Category | Response time | Details |")
    A("|---|---|---|---|---|")
    for r in results:
        icon = "✅" if r["passed"] else "❌"
        lat = max(r["latencies"]) if r["latencies"] else 0
        if r["error"]:
            detail = f"error: {r['error']}"
        else:
            fails = [c for c in r["checks"] if not c["passed"]]
            detail = "all checks passed" if not fails else \
                "; ".join(f"{c['check']} → {c['detail']}" for c in fails)
        A(f"| {icon} | {r['name']} | {r['category']} | {lat:.2f}s | {detail} |")
    A("")

    # ---- Latency overview ----------------------------------------------
    all_lat = [l for r in results for l in r["latencies"]]
    if all_lat:
        all_lat.sort()
        p95 = all_lat[min(len(all_lat) - 1, int(0.95 * (len(all_lat) - 1)))]
        A("## Response time (functional turns)")
        A("")
        A(f"- **Fastest:** {min(all_lat):.2f}s")
        A(f"- **Median:** {all_lat[len(all_lat)//2]:.2f}s")
        A(f"- **p95:** {p95:.2f}s")
        A(f"- **Slowest:** {max(all_lat):.2f}s")
        A("")

    # ---- Load test ------------------------------------------------------
    load = payload.get("load")
    if load:
        A("## Load test")
        A("")
        A(f"Ran **{load['concurrency']}** concurrent conversations.")
        A("")
        A("| Metric | Value |")
        A("|---|---|")
        A(f"| Completed | {load['completed']} |")
        A(f"| Errors | {load['errors']} |")
        A(f"| Throughput | {load['throughput_convos_per_s']} convos/s |")
        A(f"| Mean response | {load['mean_s']}s |")
        A(f"| p50 | {load['p50_s']}s |")
        A(f"| p95 | {load['p95_s']}s |")
        A(f"| Max | {load['max_s']}s |")
        A("")

    # ---- Answer quality -------------------------------------------------
    quality = payload.get("quality")
    if quality:
        A("## Answer quality (LLM judge)")
        A("")
        A("| Case | Score (1–5) | Note |")
        A("|---|---|---|")
        for q in quality:
            score = q.get("score") if q.get("scored") else "—"
            A(f"| {q.get('name', q['id'])} | {score} | {q.get('note','')} |")
        A("")

    A("---")
    A("<sub>Generated by the Copilot Studio Direct Line test harness.</sub>")

    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
