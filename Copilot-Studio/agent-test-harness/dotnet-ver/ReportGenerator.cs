// ReportGenerator.cs — turns a ReportPayload into a Markdown report (README.md).
// Designed to be committed straight to GitHub, so the repo front page always
// shows the latest run. Numbers use invariant formatting (set in Program.cs).

using System.Text;

namespace AgentTestHarness;

public static class ReportGenerator
{
    private static string Badge(int passed, int total)
    {
        string colour = passed == total ? "brightgreen" : (passed >= total * 0.7 ? "yellow" : "red");
        string label = $"{passed}%2F{total}%20passing";
        return $"![tests](https://img.shields.io/badge/tests-{label}-{colour})";
    }

    public static void WriteReport(ReportPayload payload, string path)
    {
        var results = payload.Functional;
        int passed = results.Count(r => r.Passed);
        int total = results.Count;
        var sb = new StringBuilder();

        sb.AppendLine($"# 🤖 {payload.AgentName} — Automated Test Report");
        sb.AppendLine();
        sb.AppendLine(Badge(passed, total));
        sb.AppendLine();
        sb.AppendLine($"**Last run:** {payload.GeneratedAt}  ");
        sb.AppendLine($"**Result:** {passed}/{total} functional cases passing");
        sb.AppendLine();
        sb.AppendLine("> Auto-generated by the Direct Line test harness. See **[SETUP.md](SETUP.md)** "
                      + "for how it works and how to configure it.");
        sb.AppendLine();

        // ---- Summary by category ----
        sb.AppendLine("## Summary by category");
        sb.AppendLine();
        sb.AppendLine("| Category | Passing | Total |");
        sb.AppendLine("|---|---|---|");
        foreach (var g in results.GroupBy(r => r.Category).OrderBy(g => g.Key))
            sb.AppendLine($"| {g.Key} | {g.Count(r => r.Passed)} | {g.Count()} |");
        sb.AppendLine();

        // ---- Functional detail ----
        sb.AppendLine("## Functional results");
        sb.AppendLine();
        sb.AppendLine("| | Case | Category | Response time | Details |");
        sb.AppendLine("|---|---|---|---|---|");
        foreach (var r in results)
        {
            string icon = r.Passed ? "✅" : "❌";
            double lat = r.Latencies.Count > 0 ? r.Latencies.Max() : 0;
            string detail;
            if (r.Error is not null)
            {
                detail = $"error: {r.Error}";
            }
            else
            {
                var fails = r.Checks.Where(c => !c.Passed).ToList();
                detail = fails.Count == 0
                    ? "all checks passed"
                    : string.Join("; ", fails.Select(c => $"{c.Check} → {c.Detail}"));
            }
            sb.AppendLine($"| {icon} | {r.Name} | {r.Category} | {lat:F2}s | {detail} |");
        }
        sb.AppendLine();

        // ---- Latency overview ----
        var allLat = results.SelectMany(r => r.Latencies).OrderBy(x => x).ToList();
        if (allLat.Count > 0)
        {
            double p95 = allLat[Math.Min(allLat.Count - 1, (int)(0.95 * (allLat.Count - 1)))];
            sb.AppendLine("## Response time (functional turns)");
            sb.AppendLine();
            sb.AppendLine($"- **Fastest:** {allLat.First():F2}s");
            sb.AppendLine($"- **Median:** {allLat[allLat.Count / 2]:F2}s");
            sb.AppendLine($"- **p95:** {p95:F2}s");
            sb.AppendLine($"- **Slowest:** {allLat.Last():F2}s");
            sb.AppendLine();
        }

        // ---- Load test ----
        if (payload.Load is LoadResult load)
        {
            sb.AppendLine("## Load test");
            sb.AppendLine();
            sb.AppendLine($"Ran **{load.Concurrency}** concurrent conversations.");
            sb.AppendLine();
            sb.AppendLine("| Metric | Value |");
            sb.AppendLine("|---|---|");
            sb.AppendLine($"| Completed | {load.Completed} |");
            sb.AppendLine($"| Errors | {load.Errors} |");
            sb.AppendLine($"| Throughput | {load.ThroughputConvosPerS} convos/s |");
            sb.AppendLine($"| Mean response | {load.MeanS}s |");
            sb.AppendLine($"| p50 | {load.P50S}s |");
            sb.AppendLine($"| p95 | {load.P95S}s |");
            sb.AppendLine($"| Max | {load.MaxS}s |");
            sb.AppendLine();
        }

        // ---- Answer quality ----
        if (payload.Quality.Count > 0)
        {
            sb.AppendLine("## Answer quality (LLM judge)");
            sb.AppendLine();
            sb.AppendLine("| Case | Score (1–5) | Note |");
            sb.AppendLine("|---|---|---|");
            foreach (var q in payload.Quality)
            {
                string score = q.Scored ? (q.Score?.ToString() ?? "—") : "—";
                sb.AppendLine($"| {(string.IsNullOrEmpty(q.Name) ? q.Id : q.Name)} | {score} | {q.Note} |");
            }
            sb.AppendLine();
        }

        sb.AppendLine("---");
        sb.AppendLine("<sub>Generated by the Copilot Studio Direct Line test harness (.NET).</sub>");

        File.WriteAllText(path, sb.ToString());
    }
}
